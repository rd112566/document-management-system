import os
import pymupdf as fitz
from docx import Document

samples_dir = os.path.join(os.path.dirname(__file__), "..", "samples")
os.makedirs(samples_dir, exist_ok=True)

# 1. Create Sample TXT
txt_path = os.path.join(samples_dir, "sample_ai_policy.txt")
with open(txt_path, "w", encoding="utf-8") as f:
    f.write("""Artificial Intelligence Governance Policy 2026

Section 1: Data Privacy & Security
All AI document processing systems must implement end-to-end data isolation per user.
No confidential document uploaded by User A should ever be queryable or visible to User B.
All encryption keys must use AES-256 standard, and tokens must expire within 24 hours.

Section 2: RAG Accuracy and Source Citations
Retrieval-Augmented Generation (RAG) must always include exact source metadata.
Every factual statement generated by the system must reference the originating document name and specific page number.
If information is not present in the retrieved context, the assistant must explicitly say that the answer is not found.
""")

# 2. Create Sample PDF with multiple pages
pdf_path = os.path.join(samples_dir, "quantum_computing_overview.pdf")
