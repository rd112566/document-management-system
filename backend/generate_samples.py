page2 = doc.new_page()
page2.insert_text((50, 72), "Quantum Error Correction & Algorithms - Page 2\n\nShor's algorithm can factor large integers exponentially faster than classical algorithms.\nGrover's algorithm provides a quadratic speedup for unstructured database search.\nFault-tolerant quantum computing requires surface codes with thousands of physical qubits per logical qubit.", fontsize=12)

doc.save(pdf_path)
doc.close()

